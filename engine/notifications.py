"""
engine/notifications.py
=======================
Deterministic notification-lifecycle service.

Generates STRUCTURED, SIMULATED customer-notification *previews* for four
explicit lifecycle states. It never sends anything, never enrolls anyone, and
makes no AI calls. All numeric content comes verbatim from an engine result
(via engine.formatting.format_window and the raw hour fields).

Design rules enforced here (see also docs/notifications_integration.md):
  - Scenario ELIGIBILITY (from the engine's alert_eligible) is kept SEPARATE
    from customer CONSENT (opt-in) and from CHANNEL availability. A send is only
    recommended when all three line up.
  - "Outage confirmed" and "Restoration complete" require the caller to pass the
    explicit lifecycle state. They are NEVER inferred from a High risk band or a
    zero-duration / no-damage estimate.
  - "Restoration estimate updated" uses a documented MATERIAL-CHANGE threshold
    and explicitly handles transitions to/from Unknown.
  - Missing data is reported as unknown, never invented.
  - Every preview is labeled as a simulation/preview.

Owner: Samai (engine/). Additive — existing public interfaces are unchanged.
"""

from __future__ import annotations
from typing import Optional

from engine.formatting import format_window
from engine.safety import APPROVED_SAFETY_GUIDANCE

# ---------------------------------------------------------------------------
# Lifecycle states (the ONLY accepted values for `lifecycle_state`)
# ---------------------------------------------------------------------------
PRE_STORM = "pre_storm"
OUTAGE_CONFIRMED = "outage_confirmed"
RESTORATION_UPDATED = "restoration_updated"
RESTORATION_COMPLETE = "restoration_complete"

LIFECYCLE_STATES: tuple[str, ...] = (
    PRE_STORM, OUTAGE_CONFIRMED, RESTORATION_UPDATED, RESTORATION_COMPLETE,
)

# States whose real-world meaning cannot be inferred from the scenario model and
# therefore REQUIRE the caller to assert the explicit simulated lifecycle state.
_EXPLICIT_ONLY_STATES = (OUTAGE_CONFIRMED, RESTORATION_COMPLETE)

# ---------------------------------------------------------------------------
# Documented PROTOTYPE thresholds / defaults
# (NOT verified AEP enrollment rules — prototype only.)
# ---------------------------------------------------------------------------

# Material-change threshold for "restoration estimate updated": an update is
# considered material if the window midpoint moves by at least this fraction
# OR by at least this many absolute hours (whichever is easier to satisfy).
# Any transition INTO or OUT OF "Unknown" is always treated as material.
MATERIAL_CHANGE_FRACTION = 0.25     # 25% change in the midpoint
MATERIAL_CHANGE_ABS_HOURS = 2.0     # or >= 2.0 hours absolute

# Recommended default channel per lifecycle state (prototype convention).
# Urgent states prefer SMS; informational states prefer email/push.
_DEFAULT_CHANNEL = {
    PRE_STORM: "email",
    OUTAGE_CONFIRMED: "sms",
    RESTORATION_UPDATED: "sms",
    RESTORATION_COMPLETE: "email",
}

# Recommended timing per lifecycle state (prototype convention; human-readable).
_DEFAULT_TIMING = {
    PRE_STORM: "Ahead of the simulated storm (advance notice).",
    OUTAGE_CONFIRMED: "Immediately on confirmation of the simulated outage.",
    RESTORATION_UPDATED: "When the estimate materially changes.",
    RESTORATION_COMPLETE: "On confirmation that the simulated restoration is complete.",
}

SIMULATION_LABEL = (
    "SIMULATED PREVIEW — not a real AEP message, not sent, and not a confirmed "
    "prediction or outage. Generated by StormReady for demonstration."
)


# ---------------------------------------------------------------------------
# Small helpers
# ---------------------------------------------------------------------------

def _window(result: Optional[dict]) -> tuple[Optional[float], Optional[float]]:
    if not result:
        return None, None
    return result.get("restoration_low_hours"), result.get("restoration_high_hours")


def _is_unknown(result: Optional[dict]) -> bool:
    low, high = _window(result)
    return low is None or high is None


def _is_zero_duration(result: Optional[dict]) -> bool:
    low, high = _window(result)
    return low == 0 and high == 0


def _midpoint(result: Optional[dict]) -> Optional[float]:
    low, high = _window(result)
    if low is None or high is None:
        return None
    return (low + high) / 2.0


def _window_text(result: Optional[dict]) -> str:
    low, high = _window(result)
    return format_window(low, high)


def classify_estimate_change(prev_result: Optional[dict],
                             curr_result: Optional[dict]) -> dict:
    """
    Classify the change between two restoration estimates using the documented
    material-change threshold. Handles transitions to/from Unknown.

    Returns {"kind", "material", "detail"} where kind is one of:
      "no_previous" | "to_unknown" | "from_unknown" | "both_unknown"
      | "changed" | "unchanged"
    """
    prev_unknown = _is_unknown(prev_result)
    curr_unknown = _is_unknown(curr_result)

    if prev_result is None:
        return {"kind": "no_previous", "material": False,
                "detail": "No previous estimate to compare against."}

    if prev_unknown and curr_unknown:
        return {"kind": "both_unknown", "material": False,
                "detail": "Estimate was unknown before and remains unknown."}
    if prev_unknown and not curr_unknown:
        return {"kind": "from_unknown", "material": True,
                "detail": f"Estimate became available: now {_window_text(curr_result)} "
                          "(previously unknown). Treated as a material change."}
    if curr_unknown and not prev_unknown:
        return {"kind": "to_unknown", "material": True,
                "detail": f"Estimate became unknown (previously {_window_text(prev_result)}). "
                          "Treated as a material change."}

    # Both known — compare midpoints against the documented threshold.
    pm = _midpoint(prev_result)
    cm = _midpoint(curr_result)
    abs_change = abs(cm - pm)
    frac_change = (abs_change / pm) if pm > 0 else (1.0 if abs_change > 0 else 0.0)
    material = abs_change >= MATERIAL_CHANGE_ABS_HOURS or frac_change >= MATERIAL_CHANGE_FRACTION
    direction = "longer" if cm > pm else ("shorter" if cm < pm else "unchanged")
    if abs_change == 0:
        return {"kind": "unchanged", "material": False,
                "detail": f"Estimate unchanged ({_window_text(curr_result)})."}
    return {
        "kind": "changed",
        "material": bool(material),
        "detail": (f"Estimate {direction}: {_window_text(prev_result)} → "
                   f"{_window_text(curr_result)} "
                   f"(midpoint Δ {abs_change:.1f} h, {frac_change*100:.0f}%). "
                   + ("Material per threshold." if material else "Below material threshold.")),
    }


# ---------------------------------------------------------------------------
# Message builders (deterministic; numbers come from the engine result)
# ---------------------------------------------------------------------------

def _household(inputs: dict) -> str:
    return inputs.get("customer_label", "your household")


def _pre_storm_message(inputs: dict, result: dict) -> tuple[str, str]:
    band = result.get("risk_band", "unknown")
    sev = inputs.get("storm_severity", "unknown")
    msg = (
        f"[SIMULATED PREVIEW] A {sev.upper()} storm is simulated for your area. "
        f"Under these assumed conditions, {_household(inputs)} has an estimated "
        f"{band} outage-risk level. This is a scenario estimate, not a forecast or "
        f"a confirmed outage. Consider preparing now: {APPROVED_SAFETY_GUIDANCE[3]}"
    )
    reason = f"Pre-storm advisory for a simulated {sev} storm (risk band {band})."
    return msg, reason


def _outage_confirmed_message(inputs: dict, result: dict) -> tuple[str, str]:
    msg = (
        f"[SIMULATED PREVIEW] A power outage has been marked CONFIRMED in this "
        f"simulated scenario for {_household(inputs)}. {APPROVED_SAFETY_GUIDANCE[0]} "
        f"Estimated restoration window (heuristic): {_window_text(result)}."
    )
    reason = ("Outage confirmation requested via explicit simulated lifecycle state "
              "(not inferred from risk band).")
    return msg, reason


def _restoration_updated_message(inputs: dict, result: dict,
                                 change: dict) -> tuple[str, str]:
    msg = (
        f"[SIMULATED PREVIEW] The simulated restoration estimate for {_household(inputs)} "
        f"has been updated to {_window_text(result)} (heuristic scenario range). "
        f"{change['detail']}"
    )
    reason = f"Restoration estimate update ({change['kind']}); {change['detail']}"
    return msg, reason


def _restoration_complete_message(inputs: dict, result: dict) -> tuple[str, str]:
    msg = (
        f"[SIMULATED PREVIEW] Power has been marked RESTORED in this simulated "
        f"scenario for {_household(inputs)}. If you are still without power in a real "
        f"event, report it to AEP Ohio at 1-800-672-2231. This is a preview, not a "
        f"confirmation of real service status."
    )
    reason = ("Restoration completion requested via explicit simulated lifecycle state "
              "(not inferred from a zero-duration or no-damage estimate).")
    return msg, reason


# ---------------------------------------------------------------------------
# Public helper
# ---------------------------------------------------------------------------

def build_notification_preview(
    *,
    lifecycle_state: str,
    inputs: dict,
    result: dict,
    prev_result: Optional[dict] = None,
    preferences: Optional[dict] = None,
) -> dict:
    """
    Build a single SIMULATED notification preview. Deterministic; no AI calls.

    Parameters
    ----------
    lifecycle_state : str
        One of engine.notifications.LIFECYCLE_STATES. For OUTAGE_CONFIRMED and
        RESTORATION_COMPLETE this explicit state is REQUIRED — those are never
        inferred from the scenario.
    inputs : dict
        Current scenario inputs (customer_label, storm_severity, available_crews,
        access_blocked, damage_scenario).
    result : dict
        Current engine result (from evaluate_scenario). Numbers are used verbatim.
    prev_result : dict | None
        Previous engine result, used for RESTORATION_UPDATED change classification.
    preferences : dict | None
        Customer notification preferences, SEPARATE from scenario eligibility:
          {"opted_in": bool (default True),
           "available_channels": list[str] (default ["sms","email","push"]),
           "preferred_channel": str | None}

    Returns
    -------
    dict with keys:
        lifecycle_state       str
        message               str   (always framed as a simulated preview)
        trigger_reason        str
        recommended_channel   str | None
        timing                str
        scenario_eligible     bool  (from engine result's alert_eligible)
        consent_status        str   ("opted_in" | "opted_out")
        channel_available     bool
        send_recommended      bool  (eligible AND opted_in AND channel available)
        send_blockers         list[str]  (why a send is NOT recommended, if any)
        estimate_window       str   (format_window of the current result)
        estimate_change       dict | None  (only for RESTORATION_UPDATED)
        unknowns              list[str]  (what is missing/unknown, if anything)
        simulation_label      str
        safety_guidance       list[str]
    """
    if lifecycle_state not in LIFECYCLE_STATES:
        raise ValueError(
            f"Unknown lifecycle_state {lifecycle_state!r}; "
            f"expected one of {LIFECYCLE_STATES}."
        )

    prefs = preferences or {}
    opted_in = prefs.get("opted_in", True)
    available_channels = list(prefs.get("available_channels",
                                        ["sms", "email", "push"]))
    preferred_channel = prefs.get("preferred_channel")

    unknowns: list[str] = []
    estimate_change: Optional[dict] = None

    # --- Build message + reason per state (with guardrails) ---
    if lifecycle_state == PRE_STORM:
        message, reason = _pre_storm_message(inputs, result)

    elif lifecycle_state == OUTAGE_CONFIRMED:
        # Explicitly requested. We NEVER infer this from risk band; if the risk
        # band is High that does not imply a confirmed outage — note that.
        message, reason = _outage_confirmed_message(inputs, result)
        if result.get("risk_band") in ("High", "Critical"):
            reason += (" Note: the High/Critical risk band alone does NOT confirm an "
                       "outage; confirmation here comes from the explicit simulated state.")
        if _is_unknown(result):
            unknowns.append("Restoration window is unknown for this scenario.")

    elif lifecycle_state == RESTORATION_UPDATED:
        estimate_change = classify_estimate_change(prev_result, result)
        message, reason = _restoration_updated_message(inputs, result, estimate_change)
        if estimate_change["kind"] == "no_previous":
            unknowns.append("No previous estimate provided; cannot classify the change.")
        if _is_unknown(result):
            unknowns.append("Current restoration estimate is unknown.")

    elif lifecycle_state == RESTORATION_COMPLETE:
        # Guardrail: completion must come from the explicit state, NOT from a
        # zero-duration / no-damage estimate. If the scenario is zero-duration,
        # flag the mismatch rather than implying real completion from it.
        message, reason = _restoration_complete_message(inputs, result)
        if _is_zero_duration(result):
            unknowns.append(
                "The current scenario models no repairs (0 h). A zero-duration / "
                "no-damage estimate does NOT by itself mean restoration is complete; "
                "completion here is asserted only by the explicit simulated state."
            )
        if _is_unknown(result):
            unknowns.append(
                "The restoration estimate is unknown; completion is asserted by the "
                "explicit simulated state, not derived from an estimate."
            )

    # --- Eligibility (scenario) vs consent (opt-in) vs channel (availability) ---
    scenario_eligible = bool(result.get("alert_eligible", False))
    consent_status = "opted_in" if opted_in else "opted_out"

    # Choose a recommended channel: prefer customer's preferred if available,
    # else the state's default if available, else the first available channel.
    default_channel = _DEFAULT_CHANNEL[lifecycle_state]
    recommended_channel: Optional[str] = None
    if preferred_channel and preferred_channel in available_channels:
        recommended_channel = preferred_channel
    elif default_channel in available_channels:
        recommended_channel = default_channel
    elif available_channels:
        recommended_channel = available_channels[0]
    channel_available = recommended_channel is not None

    # Send recommendation = eligibility AND consent AND channel (all separate).
    send_blockers: list[str] = []
    if not scenario_eligible:
        send_blockers.append("Scenario is not eligible under prototype alert rules.")
    if not opted_in:
        send_blockers.append("Customer has opted out (no send recommended; preview still shown).")
    if not channel_available:
        send_blockers.append("No available delivery channel.")
    send_recommended = (scenario_eligible and opted_in and channel_available)

    return {
        "lifecycle_state": lifecycle_state,
        "message": message,
        "trigger_reason": reason,
        "recommended_channel": recommended_channel,
        "timing": _DEFAULT_TIMING[lifecycle_state],
        "scenario_eligible": scenario_eligible,
        "consent_status": consent_status,
        "channel_available": channel_available,
        "send_recommended": send_recommended,
        "send_blockers": send_blockers,
        "estimate_window": _window_text(result),
        "estimate_change": estimate_change,
        "unknowns": unknowns,
        "simulation_label": SIMULATION_LABEL,
        "safety_guidance": list(APPROVED_SAFETY_GUIDANCE),
    }


def build_lifecycle_previews(
    *,
    inputs: dict,
    result: dict,
    prev_result: Optional[dict] = None,
    preferences: Optional[dict] = None,
) -> dict:
    """
    Convenience: build previews for all four lifecycle states at once.
    Returns {state: preview_dict}. Note OUTAGE_CONFIRMED / RESTORATION_COMPLETE
    previews here still represent EXPLICIT simulated states (the caller is asking
    to preview them), consistent with build_notification_preview's contract.
    """
    return {
        state: build_notification_preview(
            lifecycle_state=state, inputs=inputs, result=result,
            prev_result=prev_result, preferences=preferences,
        )
        for state in LIFECYCLE_STATES
    }
